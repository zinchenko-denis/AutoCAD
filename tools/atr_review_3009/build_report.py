def shade(cell, fill):
    props = cell._tc.get_or_add_tcPr()
    item = OxmlElement("w:shd")
    item.set(qn("w:fill"), fill)
    props.append(item)


def keep_row(row):
    props = row._tr.get_or_add_trPr()
    props.append(OxmlElement("w:cantSplit"))


def table(doc, headers, rows, widths):
    tab = doc.add_table(rows=1, cols=len(headers))
    tab.alignment = WD_TABLE_ALIGNMENT.CENTER
    tab.autofit = False
    props = tab._tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        item = OxmlElement("w:" + edge)
        item.set(qn("w:val"), "single")
        item.set(qn("w:sz"), "5")
        item.set(qn("w:color"), "D9D9D9")
        borders.append(item)
    props.append(borders)
    margins = OxmlElement("w:tblCellMar")
    for edge, value in (("top", 100), ("bottom", 100), ("left", 110), ("right", 110)):
        item = OxmlElement("w:" + edge)
        item.set(qn("w:w"), str(value))
        item.set(qn("w:type"), "dxa")
        margins.append(item)
    props.append(margins)
    for i, width in enumerate(widths):
        tab.columns[i].width = Mm(width)
    for i, heading in enumerate(headers):
        tab.rows[0].cells[i].text = heading
        shade(tab.rows[0].cells[i], "E7E7E7")
    repeat = OxmlElement("w:tblHeader")
    tab.rows[0]._tr.get_or_add_trPr().append(repeat)
    for values in rows:
        row = tab.add_row()
        for i, text in enumerate(values):
            row.cells[i].text = str(text)
    for ridx, row in enumerate(tab.rows):
        keep_row(row)
        for i, cell in enumerate(row.cells):
            cell.width = Mm(widths[i])
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            for p in cell.paragraphs:
                p.paragraph_format.space_before = Pt(0)
                p.paragraph_format.space_after = Pt(0)
                p.paragraph_format.line_spacing = 1.03
                if i == 0 and widths[i] <= 25:
                    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                for run in p.runs:
                    run.font.name = "Arial"
                    run.font.size = Pt(10.5)
                    run.font.bold = ridx == 0
                    run.font.color.rgb = RGBColor(0, 0, 0)
    doc.add_paragraph().paragraph_format.space_after = Pt(1)
    return tab


def para(doc, text, bold_start=None, style=None):
    p = doc.add_paragraph(style=style)
    if bold_start and text.startswith(bold_start):
        p.add_run(bold_start).bold = True
        p.add_run(text[len(bold_start):])
    else:
        p.add_run(text)
    return p


def heading(doc, text, level=1):
    return doc.add_heading(text, level)


def next_page(doc, title):
    doc.add_page_break()
    heading(doc, title)


