def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--facts", type=Path)
    args = ap.parse_args()
    facts = json.loads(args.facts.read_text(encoding="utf-8")) if args.facts else {}
    if not isinstance(facts, dict):
        raise ValueError("facts must be a JSON object")
    source_hashes = {}
    for name in SOURCES:
        path = ROOT / "docs/atr_review_3009" / name
        source_hashes[str(path.relative_to(ROOT))] = hashlib.sha256(path.read_bytes()).hexdigest()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    make_document(facts).save(args.out)
    manifest = {"document": args.out.name, "facts_supplied": bool(args.facts),
                "facts_sha256": hashlib.sha256(args.facts.read_bytes()).hexdigest() if args.facts else None,
                "source_sha256": source_hashes, "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                "verification_claims": "supplied facts only; missing groups remain pending"}
    args.out.with_suffix(".manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(args.out)


if __name__ == "__main__":
    main()
