def build(path):
    doc = BaseDocTemplate(path, pagesize=A4, leftMargin=16 * mm, rightMargin=14 * mm,
                          topMargin=14 * mm, bottomMargin=14 * mm,
                          title="AClad — сборка №20 (23.09): ATTILE, универсальная разбежка",
                          author="Denis Zinchenko")
    fr = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height)
    doc.addPageTemplates([PageTemplate(id="page", frames=[fr])])
    doc.build(story)
    print("OK:", path, os.path.getsize(path), "bytes")


