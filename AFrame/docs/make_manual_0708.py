def build(path):
    doc = BaseDocTemplate(
        path, pagesize=A4,
        leftMargin=18 * mm, rightMargin=15 * mm,
        topMargin=16 * mm, bottomMargin=16 * mm,
        title="AFrame — сборка №18 (07.08)",
        author="Denis Zinchenko")
    fr = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height)
    doc.addPageTemplates([PageTemplate(id="page", frames=[fr])])
    story = []
    for kind, text in CONTENT:
        story.append(Paragraph(text, S[kind]))
        if kind == "h1":
            story.append(Spacer(1, 2 * mm))
    doc.build(story)
    print("OK:", path, os.path.getsize(path), "bytes")


