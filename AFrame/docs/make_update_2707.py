def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "AFRAME_update_2707.pdf")
    doc = BaseDocTemplate(out, pagesize=A4,
                          leftMargin=18 * mm, rightMargin=15 * mm,
                          topMargin=15 * mm, bottomMargin=15 * mm,
                          title="Фасады НВФ — обновление 27.07",
                          author="AFrame/AClad/AFacades")
    fr = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height)
    doc.addPageTemplates([PageTemplate(id="p", frames=[fr])])
    story = []
    for kind, text in CONTENT:
        story.append(Paragraph(text, S[kind]))
        if kind == "h1":
            story.append(Spacer(1, 2 * mm))
    doc.build(story)
    print("OK:", out)


if __name__ == "__main__":
    main()
