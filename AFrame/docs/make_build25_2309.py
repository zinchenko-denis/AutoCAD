def _frame(canvas, doc):
    canvas.saveState()
    canvas.setFont("DV", 8)
    canvas.drawString(15 * mm, 10 * mm, "Сборка №25 (build-bundle #%s, коммит %s) · 23.09.2026 · стр. %d" % (BUILD, SHA, doc.page))
    canvas.restoreState()


